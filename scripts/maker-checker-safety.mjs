const shellExclusion = '--excluded-tools=shell';
const urlDenial = '--deny-tool=url';
const javascriptTrivia = String.raw`(?:\s|\/\*[\s\S]*?\*\/|\/\/[^\r\n]*(?:\r?\n|$))*`;
const sandboxCompatibleShellScripts = new Set([
  'scripts/check-architecture.sh',
]);
// Build output directories are regenerated by routine builds, so hashing them
// would report a boundary violation on every round.
const digestSkippedDirectories = new Set(['bin', 'obj']);
// Verification roots are hashed whole instead of discovering inputs by parsing
// imports. Repository-root files are covered individually so that a helper next
// to the solution file stays protected without recursing into directories that
// change during a normal round, such as .git/, .local/, docs/, and src/.
const verificationProtectedRoots = ['scripts', 'tests'];
const executableLoaderModules = new Set([
  'child_process',
  'node:child_process',
  'cluster',
  'node:cluster',
  'worker_threads',
  'node:worker_threads',
]);
const nodeBuiltins = new Set(
  builtinModules.flatMap((moduleName) => [
    moduleName,
    moduleName.replace(/^node:/, ''),
    `node:${moduleName.replace(/^node:/, '')}`,
  ]),
);

